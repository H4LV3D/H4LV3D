// Generates single-stroke handwriting paths (used for the signature logo and
// preloader) from the EMS Allure Hershey-style font (SIL OFL, via `hersheytext`).
// Usage: node scripts/generate-signature.mjs <path-to-EMSAllure.svg> "Toluwalope" signature
import { readFileSync } from "node:fs";

const [, , fontPath, text = "Toluwalope", exportName = "signature"] = process.argv;
const svg = readFileSync(fontPath, "utf8");
const glyphs = new Map();
for (const m of svg.matchAll(/<glyph unicode="([^"]+)"[^>]*?horiz-adv-x="([\d.]+)"(?:[^>]*?d="([^"]*)")?/g)) {
  glyphs.set(m[1], { adv: Number(m[2]), d: m[3] ?? "" });
}

const strokes = [];
let x = 0;
for (const ch of text) {
  const g = glyphs.get(ch);
  if (!g) throw new Error(`Missing glyph ${ch}`);
  for (const part of g.d
    .split("M")
    .map((s) => s.trim())
    .filter(Boolean)) {
    const nums = part.replace(/L/g, " ").trim().split(/\s+/).map(Number);
    const pts = [];
    for (let i = 0; i < nums.length; i += 2) pts.push([nums[i] + x, -nums[i + 1]]);
    strokes.push(pts);
  }
  x += g.adv;
}

// Catmull-Rom → cubic Bézier for a smooth, ink-like line.
const r = (n) => Math.round(n * 10) / 10;
function smooth(pts) {
  if (pts.length < 3) return `M${pts.map((p) => p.map(r).join(" ")).join(" L")}`;
  let d = `M${r(pts[0][0])} ${r(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] ?? pts[i];
    const p1 = pts[i];
    const p2 = pts[i + 1];
    const p3 = pts[i + 2] ?? p2;
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += ` C${r(c1[0])} ${r(c1[1])} ${r(c2[0])} ${r(c2[1])} ${r(p2[0])} ${r(p2[1])}`;
  }
  return d;
}

const all = strokes.flat();
const minX = Math.min(...all.map((p) => p[0]));
const minY = Math.min(...all.map((p) => p[1]));
const maxX = Math.max(...all.map((p) => p[0]));
const maxY = Math.max(...all.map((p) => p[1]));
const pad = 20;
const shifted = strokes.map((s) => s.map(([px, py]) => [px - minX + pad, py - minY + pad]));
const viewBox = `0 0 ${Math.ceil(maxX - minX + pad * 2)} ${Math.ceil(maxY - minY + pad * 2)}`;

console.log(`// Generated by scripts/generate-signature.mjs — do not edit by hand.
// Source font: EMS Allure (SIL Open Font License), via the \`hersheytext\` package.
export const ${exportName} = {
  viewBox: "${viewBox}",
  paths: ${JSON.stringify(shifted.map(smooth), null, 2)},
} as const;`);
