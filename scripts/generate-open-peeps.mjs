// Pre-renders the Open Peeps (https://www.openpeeps.com, CC0, via react-peeps)
// used on the site into plain SVG strings, so no illustration library ships
// to the browser. Lines become currentColor and fills var(--peep-fill), so
// the peeps follow the theme.
//
// Edit PEEPS below, then: node scripts/generate-open-peeps.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import PeepModule from "react-peeps";

const Peep = PeepModule.default ?? PeepModule;

// Toluwalope: short messy hair and a goatee.
const LOOK = { hair: "ShortMessy", facialHair: "Goatee" };

const PEEPS = {
  coffee: { body: "Coffee", face: "Smile" },
  phone: { body: "Device", face: "Calm" },
  pointing: { body: "PointingUp", face: "SmileBig" },
  shrug: { body: "Whatever", face: "Concerned" },
  explaining: { body: "Explaining", face: "Smile" },
  armsCrossed: { body: "ArmsCrossed", face: "Smile" },
};

const INK = "#010203";
const PAPER = "#fdfeff";

const out = {};
for (const [name, props] of Object.entries(PEEPS)) {
  const svg = renderToStaticMarkup(
    React.createElement(Peep, { ...LOOK, ...props, strokeColor: INK, backgroundColor: PAPER }),
  );
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replaceAll(INK, "currentColor")
    .replaceAll(PAPER, "var(--peep-fill)");
  out[name] = { viewBox, body };
}

// One module per peep, so a component only ships the peep it shows.
const dir = "src/components/illustrations/open-peeps/generated";
mkdirSync(dir, { recursive: true });
for (const [name, def] of Object.entries(out)) {
  writeFileSync(
    `${dir}/${name}.ts`,
    `// Generated by scripts/generate-open-peeps.mjs. Do not edit by hand.
// Open Peeps by Pablo Stanley (CC0), rendered with react-peeps (MIT).
export const peep = ${JSON.stringify(def)} as const;
`,
  );
}
console.log("wrote", Object.keys(out).join(", "));
