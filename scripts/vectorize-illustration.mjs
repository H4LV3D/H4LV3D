// Turns a black-on-white line illustration (PNG/JPG/WebP) into SVG paths so
// it can be themed and animated:
//   ink        — the linework (render with fill-rule="evenodd")
//   silhouette — the figure's paper cut-out (everything not reachable from
//                the image border), drawn behind the ink
//
// Usage: node scripts/vectorize-illustration.mjs <image> <name>
//   → writes src/components/illustrations/art/<name>.ts
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { promisify } from "node:util";
import potrace from "potrace";

const require = createRequire(import.meta.url);
// sharp ships with Next.js; resolve it through Next so no extra dependency is needed.
const sharp = require(require.resolve("sharp", { paths: [require.resolve("next")] }));

const [, , input, name] = process.argv;
if (!input || !name) {
  console.error("Usage: node scripts/vectorize-illustration.mjs <image> <name>");
  process.exit(1);
}

// Flatten transparency onto white, trim the empty margin (no padding, so
// parts cropped by the image edge stay touching it), upscale for a smoother trace.
const { data, info } = await sharp(input)
  .flatten({ background: "#ffffff" })
  .trim({ background: "#ffffff", threshold: 20 })
  .resize({ width: 1400, kernel: "lanczos3" })
  .greyscale()
  .png()
  .toBuffer({ resolveWithObject: true });

const trace = promisify(potrace.trace);
const pathOf = (svg) => {
  const d = svg.match(/ d="([^"]+)"/)?.[1];
  if (!d) throw new Error("No path produced");
  // Round coordinates to 1 decimal to keep the module small.
  return d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
};

const ink = pathOf(await trace(data, { threshold: 160, turdSize: 6, optTolerance: 0.3, alphaMax: 1 }));

// Silhouette: flood-fill the white background from the border; whatever the
// fill can't reach is the figure. The ink is thickened first (closing small
// gaps, and giving the cut-out a thin sticker margin), and along each border
// only the stretch outside the outermost ink is seeded, so parts of the
// drawing that run off the edge (a cropped torso or laptop) count as inside.
const { data: px, info: raw } = await sharp(data).blur(5).threshold(245).raw().toBuffer({ resolveWithObject: true });
const { width: w, height: h, channels: ch } = raw;
const light = (i) => px[i * ch] > 200;
const outside = new Uint8Array(w * h);
const queue = [];
const seedEdge = (indices) => {
  const ink = indices.map((i) => !light(i));
  const first = ink.indexOf(true);
  const last = ink.lastIndexOf(true);
  indices.forEach((i, k) => {
    if (first === -1 || k < first || k > last) queue.push(i);
  });
};
const range = (n, f) => Array.from({ length: n }, (_, k) => f(k));
seedEdge(range(w, (x) => x)); // top
seedEdge(range(w, (x) => (h - 1) * w + x)); // bottom
seedEdge(range(h, (y) => y * w)); // left
seedEdge(range(h, (y) => y * w + w - 1)); // right
while (queue.length) {
  const i = queue.pop();
  if (outside[i] || !light(i)) continue;
  outside[i] = 1;
  const x = i % w;
  if (x > 0) queue.push(i - 1);
  if (x < w - 1) queue.push(i + 1);
  if (i >= w) queue.push(i - w);
  if (i < w * (h - 1)) queue.push(i + w);
}
const mask = Buffer.alloc(w * h);
for (let i = 0; i < w * h; i++) mask[i] = outside[i] ? 255 : 0;
const maskPng = await sharp(mask, { raw: { width: w, height: h, channels: 1 } })
  .png()
  .toBuffer();
const silhouette = pathOf(await trace(maskPng, { threshold: 128, turdSize: 200, optTolerance: 1 }));

const out = `// Generated by scripts/vectorize-illustration.mjs from ${input.split("/").pop()} — do not edit by hand.
export const ${name} = {
  viewBox: "0 0 ${info.width} ${info.height}",
  ink: "${ink}",
  silhouette: "${silhouette}",
} as const;
`;
const file = `src/components/illustrations/art/${name}.ts`;
writeFileSync(file, out);
console.log(`${file}: ${info.width}×${info.height}, ${(out.length / 1024).toFixed(1)} KB`);
